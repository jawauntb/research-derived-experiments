def symmetry_of(
    y_fn: Callable[[World], Feature],
    worlds: Sequence[World],
    ambient: Sequence[Perm] | None = None,
) -> tuple[Perm, ...]:
    """``G_Y = {g in S_4 : Y(g x) = Y(x) for all x}``."""

    if ambient is None:
        ambient = all_perms()
    return tuple(
        perm
        for perm in ambient
        if all(y_fn(apply_perm(perm, x)) == y_fn(x) for x in worlds)
    )


