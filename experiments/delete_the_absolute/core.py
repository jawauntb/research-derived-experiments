def path_a_seq(x: World) -> World:
    """Path A on sequences: drop index 0, write default 0 there."""

    return (0,) + tuple(x[1:])


def path_b_seq(x: World) -> int:
    """Path B on sequences: remember ``x[1] - x[0]`` as an ``int``, drop the absolute."""

    return int(x[1]) - int(x[0])


def path_a_pair(pair: tuple[int, int]) -> tuple[int, int]:
    """Path A on ``(i, j)``: drop the first coordinate, write default 0."""

    return (0, pair[1])


def path_b_pair(pair: tuple[int, int]) -> int:
    """Path B on ``(i, j)``: remember ``j - i`` as an ``int``, drop the absolute."""

    return int(pair[1]) - int(pair[0])


def find_sequence_noncommute_witness(
    worlds: Sequence[World],
) -> tuple[World, World] | None:
    """Two states that agree on Path A and disagree on Path B."""

    for x, xp in combinations(worlds, 2):
        if path_a_seq(x) == path_a_seq(xp) and path_b_seq(x) != path_b_seq(xp):
            return x, xp
    return None


# ---------------------------------------------------------------------------
# Positional holonomy (Lean cycle_integrates_iff_sum_zero, uniqueness)
# ---------------------------------------------------------------------------


def prefix_potentials(steps: Sequence[int], start: int = 0) -> list[int]:
    """Discrete integral: ``p[0] = start``, ``p[i+1] = p[i] + steps[i]``."""

    values = [int(start)]
    for step in steps:
        values.append(values[-1] + int(step))
    return values


def sum_int(steps: Sequence[int]) -> int:
    total = 0
    for step in steps:
        total += int(step)
    return total


def cycle_closes(steps: Sequence[int]) -> bool:
    potentials = prefix_potentials(steps, start=0)
    return potentials[len(steps)] == 0


def potentials_differ_by_constant(
    steps: Sequence[int], p0: int, q0: int
) -> tuple[bool, int]:
    """Two integrals of the same steps differ by ``p0 - q0`` at every index."""

    p_vals = prefix_potentials(steps, start=p0)
    q_vals = prefix_potentials(steps, start=q0)
    constant = int(p0) - int(q0)
    ok = all(p == q + constant for p, q in zip(p_vals, q_vals, strict=True))
    return ok, constant


