def fibres_of(
    worlds: Sequence[World], q_fn: Callable[[World], Feature]
) -> dict[Feature, list[World]]:
    cells: dict[Feature, list[World]] = {}
    for x in worlds:
        cells.setdefault(q_fn(x), []).append(x)
    return cells


def fiber_count(worlds: Sequence[World], q_fn: Callable[[World], Feature]) -> int:
    return len(fibres_of(worlds, q_fn))


def y_constant_on_fibers(
    worlds: Sequence[World],
    q_fn: Callable[[World], Feature],
    y_fn: Callable[[World], Feature],
) -> bool:
    """True iff ``Y`` factors through ``q`` (constant on every fibre)."""

    seen: dict[Feature, Feature] = {}
    for x in worlds:
        qx = q_fn(x)
        yx = y_fn(x)
        if qx in seen:
            if seen[qx] != yx:
                return False
        else:
            seen[qx] = yx
    return True


def is_representable(
    worlds: Sequence[World], model_id: str, task_id: str
) -> bool:
    return y_constant_on_fibers(worlds, MODEL_FNS[model_id], TASK_FNS[task_id])


def mixed_fibers(
    worlds: Sequence[World],
    q_fn: Callable[[World], Feature],
    y_fn: Callable[[World], Feature],
) -> list[dict[str, Any]]:
    """Fibres of ``q`` on which ``Y`` takes at least two values."""

    records: list[dict[str, Any]] = []
    for q_value, members in fibres_of(worlds, q_fn).items():
        y_values = {y_fn(x) for x in members}
        if len(y_values) > 1:
            records.append(
                {
                    "q_value": q_value,
                    "members": list(members),
                    "y_values": sorted(y_values),
                }
            )
    records.sort(key=lambda rec: rec["q_value"])
    return records


def is_exact_repair(
    worlds: Sequence[World],
    q_fn: Callable[[World], Feature],
    r_fn: Callable[[World], Feature],
    y_fn: Callable[[World], Feature],
) -> bool:
    """``Y`` factors through ``(q, r)``: Lean ``ExactRepair``."""

    for x, xp in product(worlds, worlds):
        if q_fn(x) == q_fn(xp) and r_fn(x) == r_fn(xp) and y_fn(x) != y_fn(xp):
            return False
    return True


def repair_splits_disagreement(
    worlds: Sequence[World],
    q_fn: Callable[[World], Feature],
    r_fn: Callable[[World], Feature],
    y_fn: Callable[[World], Feature],
) -> bool:
    """If ``q(x)=q(x')`` and ``Y(x)≠Y(x')``, then ``r(x)≠r(x')``."""

    for x, xp in product(worlds, worlds):
        if q_fn(x) == q_fn(xp) and y_fn(x) != y_fn(xp) and r_fn(x) == r_fn(xp):
            return False
    return True


# ---------------------------------------------------------------------------
# Repair paths (Lean repair_paths_disagree)
