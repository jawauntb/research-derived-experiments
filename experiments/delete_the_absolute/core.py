def all_worlds() -> tuple[World, ...]:
    """Enumerate ``X = {0, 1}^4`` in lexicographic order."""

    return tuple(product((0, 1), repeat=N))


def apply_perm(perm: Perm, x: World) -> World:
    """Act by rearranging positions: ``(g·x)_i = x[perm[i]]``.

    Rotate-left is ``perm = (1, 2, 3, 0)``, sending
    ``(x0, x1, x2, x3)`` to ``(x1, x2, x3, x0)``.
    """

    return tuple(x[perm[i]] for i in range(N))


def all_perms() -> tuple[Perm, ...]:
    """``S_4`` as source-index 4-tuples, lexicographic."""

    return tuple(permutations(range(N)))


def identity_perm() -> Perm:
    return tuple(range(N))


def rotate_left_perm(k: int) -> Perm:
    """``k``-fold rotate-left: position ``i`` reads former position ``i+k``."""

    return tuple((i + k) % N for i in range(N))


def group_id() -> tuple[Perm, ...]:
    return (identity_perm(),)


def group_rot() -> tuple[Perm, ...]:
    return tuple(rotate_left_perm(k) for k in range(N))


def group_perm() -> tuple[Perm, ...]:
    return all_perms()


def group_stab0() -> tuple[Perm, ...]:
    """Stabilizer of index 0: ``(g·x)[0] = x[0]`` for every ``x``, i.e. ``perm[0] = 0``."""

    return tuple(perm for perm in all_perms() if perm[0] == 0)


def orbit(x: World, group: Sequence[Perm]) -> frozenset[World]:
    return frozenset(apply_perm(perm, x) for perm in group)


def orbit_canonical(x: World, group: Sequence[Perm]) -> World:
    """Lexicographically least element of the ``G``-orbit of ``x``."""

    return min(apply_perm(perm, x) for perm in group)


def is_subset_group(small: Sequence[Perm], big: Sequence[Perm]) -> bool:
    return set(small) <= set(big)


def group_intersection(left: Sequence[Perm], right: Sequence[Perm]) -> tuple[Perm, ...]:
    right_set = set(right)
    return tuple(perm for perm in left if perm in right_set)


