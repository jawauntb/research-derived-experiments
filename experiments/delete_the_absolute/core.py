def _as_list(value: Any) -> Any:
    if isinstance(value, tuple):
        return [_as_list(item) for item in value]
    if isinstance(value, list):
        return [_as_list(item) for item in value]
    return value


def representability_matrix(worlds: Sequence[World]) -> dict[str, dict[str, bool]]:
    return {
        model_id: {
            task_id: is_representable(worlds, model_id, task_id)
            for task_id in TASK_IDS
        }
        for model_id in MODEL_IDS
    }


def inclusion_matrix(
    worlds: Sequence[World],
    task_groups: dict[str, tuple[Perm, ...]],
    model_ids: Sequence[str] = ALL_MODEL_IDS,
) -> dict[str, dict[str, bool]]:
    return {
        model_id: {
            task_id: is_subset_group(MODEL_GROUPS[model_id](), task_groups[task_id])
            for task_id in TASK_IDS
        }
        for model_id in model_ids
    }


def evaluate_nogo(
    worlds: Sequence[World],
    inclusions: dict[str, dict[str, bool]],
    model_ids: Iterable[str] = ALL_MODEL_IDS,
) -> dict[str, Any]:
    """Every ``G_M`` notsubseteq ``G_Y`` cell is unrepresentable."""

    violations: list[dict[str, Any]] = []
    checked = 0
    for model_id in model_ids:
        for task_id in TASK_IDS:
            if inclusions[model_id][task_id]:
                continue
            checked += 1
            if is_representable(worlds, model_id, task_id):
                violations.append({"model": model_id, "task": task_id})
    return {
        "passed": len(violations) == 0 and checked > 0,
        "n_mismatch_cells": checked,
        "violations": violations,
    }


def evaluate_safe(
    worlds: Sequence[World],
    inclusions: dict[str, dict[str, bool]],
    model_ids: Iterable[str] = ALL_MODEL_IDS,
) -> dict[str, Any]:
    """Every ``G_M ⊆ G_Y`` cell is representable."""

    violations: list[dict[str, Any]] = []
    checked = 0
    for model_id in model_ids:
        for task_id in TASK_IDS:
            if not inclusions[model_id][task_id]:
                continue
            checked += 1
            if not is_representable(worlds, model_id, task_id):
                violations.append({"model": model_id, "task": task_id})
    return {
        "passed": len(violations) == 0 and checked > 0,
        "n_safe_cells": checked,
        "violations": violations,
    }


def evaluate_overrepair_cost(worlds: Sequence[World]) -> dict[str, Any]:
    n_id = fiber_count(worlds, q_id)
    n_perm = fiber_count(worlds, q_perm)
    n_rot = fiber_count(worlds, q_rot)
    return {
        "passed": n_id == 16 and n_perm == 5 and n_id > n_perm,
        "q_id_fibers": n_id,
        "q_perm_fibers": n_perm,
        "q_rot_fibers": n_rot,
        "strictly_more_id_than_perm": n_id > n_perm,
    }


def evaluate_minimal_safe(
    worlds: Sequence[World],
    task_groups: dict[str, tuple[Perm, ...]],
) -> dict[str, Any]:
    g_rot = group_rot()
    g_first = task_groups["first_bit"]
    intersection = group_intersection(g_rot, g_first)
    stab_ok = is_representable(worlds, "q_stab0", "first_bit")
    perm_blocked = not is_representable(worlds, "q_perm", "first_bit")
    rot_blocked = not is_representable(worlds, "q_rot", "first_bit")
    only_identity = intersection == group_id()
    return {
        "passed": stab_ok and perm_blocked and rot_blocked and only_identity,
        "q_stab0_representable_first_bit": stab_ok,
        "q_perm_representable_first_bit": not perm_blocked,
        "q_rot_representable_first_bit": not rot_blocked,
        "G_rot_cap_G_first": [_as_list(perm) for perm in intersection],
        "intersection_is_identity": only_identity,
    }


def evaluate_repair_debt(worlds: Sequence[World]) -> dict[str, Any]:
    mixed = mixed_fibers(worlds, q_perm, y_first_bit)
    r_exact = is_exact_repair(worlds, q_perm, y_first_bit, y_first_bit)
    split_ok = repair_splits_disagreement(worlds, q_perm, y_first_bit, y_first_bit)
    constant_r = is_exact_repair(worlds, q_perm, lambda _x: 0, y_first_bit)
    witness = None
    if mixed:
        cell = mixed[0]
        members = cell["members"]
        pair = next(
            (a, b)
            for a, b in combinations(members, 2)
            if y_first_bit(a) != y_first_bit(b)
        )
        witness = {
            "q_value": _as_list(cell["q_value"]),
            "members": [_as_list(m) for m in members],
            "y_values": cell["y_values"],
            "disagreeing_pair": [_as_list(pair[0]), _as_list(pair[1])],
            "r_splits_pair": y_first_bit(pair[0]) != y_first_bit(pair[1]),
        }
    return {
        "passed": bool(mixed) and r_exact and split_ok and not constant_r,
        "n_mixed_fibers": len(mixed),
        "mixed_fiber_witness": witness,
        "r_first_bit_is_exact_repair": r_exact,
        "split_property_holds": split_ok,
        "constant_r_is_not_exact_repair": not constant_r,
    }


def evaluate_noncommute(worlds: Sequence[World]) -> dict[str, Any]:
    seq_witness = find_sequence_noncommute_witness(worlds)
    lean_p = (0, 1)
    lean_q = (1, 1)
    pair_agrees = path_a_pair(lean_p) == path_a_pair(lean_q)
    pair_disagrees = path_b_pair(lean_p) != path_b_pair(lean_q)
    seq_ok = seq_witness is not None
    record: dict[str, Any] = {
        "passed": seq_ok and pair_agrees and pair_disagrees,
        "pair_witness": {
            "p": list(lean_p),
            "q": list(lean_q),
            "path_a_p": list(path_a_pair(lean_p)),
            "path_a_q": list(path_a_pair(lean_q)),
            "path_b_p": path_b_pair(lean_p),
            "path_b_q": path_b_pair(lean_q),
            "agree_on_path_a": pair_agrees,
            "disagree_on_path_b": pair_disagrees,
        },
        "sequence_witness": None,
    }
    if seq_witness is not None:
        x, xp = seq_witness
        record["sequence_witness"] = {
            "x": list(x),
            "xp": list(xp),
            "path_a_x": list(path_a_seq(x)),
            "path_a_xp": list(path_a_seq(xp)),
            "path_b_x": path_b_seq(x),
            "path_b_xp": path_b_seq(xp),
            "agree_on_path_a": path_a_seq(x) == path_a_seq(xp),
            "disagree_on_path_b": path_b_seq(x) != path_b_seq(xp),
        }
    return record


def evaluate_positional_holonomy() -> dict[str, Any]:
    zero_closes = cycle_closes(ZERO_SUM_CYCLE)
    zero_sum = sum_int(ZERO_SUM_CYCLE)
    nonzero_closes = cycle_closes(NONZERO_SUM_CYCLE)
    nonzero_sum = sum_int(NONZERO_SUM_CYCLE)
    iff_zero = (zero_closes and zero_sum == 0) and (
        (not nonzero_closes) and nonzero_sum != 0
    )
    unique_ok, constant = potentials_differ_by_constant(
        ZERO_SUM_CYCLE, HOLONOMY_P0, HOLONOMY_Q0
    )
    unique_nz, constant_nz = potentials_differ_by_constant(
        NONZERO_SUM_CYCLE, HOLONOMY_P0, HOLONOMY_Q0
    )
    return {
        "passed": iff_zero and unique_ok and unique_nz,
        "zero_sum_cycle": list(ZERO_SUM_CYCLE),
        "zero_sum": zero_sum,
        "zero_sum_prefix": prefix_potentials(ZERO_SUM_CYCLE, start=0),
        "zero_sum_closes": zero_closes,
        "nonzero_sum_cycle": list(NONZERO_SUM_CYCLE),
        "nonzero_sum": nonzero_sum,
        "nonzero_sum_prefix": prefix_potentials(NONZERO_SUM_CYCLE, start=0),
        "nonzero_sum_closes": nonzero_closes,
        "uniqueness_p0": HOLONOMY_P0,
        "uniqueness_q0": HOLONOMY_Q0,
        "uniqueness_constant": constant,
        "uniqueness_holds_on_zero_sum": unique_ok,
        "uniqueness_holds_on_nonzero_sum": unique_nz,
        "uniqueness_constant_nonzero_cycle": constant_nz,
    }


