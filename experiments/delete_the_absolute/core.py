"""Exact finite witness of symmetry-matching delete/repair on {0,1}^4.

Companion instrument to the mathlib-free Lean core
``formal/structural-intelligence/StructuralIntelligence/DeleteRepair.lean``.

World
-----

``X = {0, 1}^4``, ``|X| = 16``.  Groups act by permuting positions:

- ``G_id = {e}``
- ``G_rot = Z/4`` generated by rotate-left
- ``G_perm = S_4`` (all 24 permutations)
- ``G_stab0 = Stab(0)`` (permutations that keep the source of index 0
  fixed; used only for the minimal-safe gate)

Models are orbit-canonical maps ``q_G(x) = lex-least element of G·x``:

- ``q_id(x) = x``
- ``q_rot(x) =`` lexicographically least rotation of ``x``
- ``q_perm(x) =`` sorted tuple (same fibres as popcount / the bit histogram)
- ``q_stab0(x) = (x[0],) + sorted(x[1:])``

Tasks ``Y``, with ``G_Y = {g in S_4 : Y(g x) = Y(x) for all x}`` computed
by enumeration:

- ``bag`` / popcount: ``Y(x) = sum(x)``.  ``G_Y = S_4``
- ``necklace``: ``Y(x) =`` lex-least rotation.  ``G_Y`` contains ``Z/4``,
  not all of ``S_4``
- ``first_bit``: ``Y(x) = x[0]``.  ``G_Y = Stab(0)``
- ``identity``: ``Y(x) = x``.  ``G_Y = {e}``

Representability
----------------

``Y`` is representable from ``q`` iff ``Y`` is constant on ``q``-fibres.
For orbit-canonical ``q_G`` this is equivalent to ``G ⊆ G_Y``.

Gates (noncompensatory)
-----------------------

1. ``DTA_NOGO`` — every ``(G, Y)`` with ``G`` notsubseteq ``G_Y`` is
   unrepresentable (over-invariance / symmetry-mismatch no-go).
2. ``DTA_SAFE`` — every ``(G, Y)`` with ``G ⊆ G_Y`` is representable
   (including leftover privilege: a finer screen still factors).
3. ``DTA_OVERREPAIR_COST`` — on popcount, ``q_id`` has strictly more
   fibres than ``q_perm`` (16 vs 5).  This is a *cost*, not a no-go.
4. ``DTA_MINIMAL_SAFE`` — for ``first_bit``, the ``Stab(0)`` orbit map
   is representable and ``q_perm`` is not.  ``G_rot ∩ G_first = {e}``,
   so ``q_rot`` is not representable for ``first_bit``.
5. ``DTA_REPAIR_DEBT`` — ``q_perm`` fibres mix ``first_bit`` values;
   any exact repair ``r`` must split those pairs.  Witnessed with
   ``r = first_bit`` itself (Lean ``repair_splits_disagreement``).
6. ``DTA_NONCOMMUTE`` — delete-then-default (Path A) and
   relative-then-drop (Path B) disagree on a finite pair (Lean
   ``repair_paths_disagree``, on sequences and on ``(i, j)`` pairs).
7. ``DTA_POSITIONAL_HOLONOMY`` — a 4-cycle of ``Int`` steps closes
   (prefix returns to 0) iff the steps sum to 0; two potentials for
   the same steps differ by a constant.

No neural training, no SGD, no PRNG.  Every check is a finite
enumeration or an integer identity.
"""

