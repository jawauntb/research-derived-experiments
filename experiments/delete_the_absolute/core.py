def q_id(x: World) -> World:
    return x


def q_rot(x: World) -> World:
    return orbit_canonical(x, group_rot())


def q_perm(x: World) -> World:
    """Sorted tuple.  Same fibres as the bit histogram / popcount."""

    return tuple(sorted(x))


def q_stab0(x: World) -> World:
    """Orbit-canonical map for ``Stab(0)``: keep bit 0, sort the rest."""

    return (x[0],) + tuple(sorted(x[1:]))


def popcount(x: World) -> int:
    return int(sum(x))


