"""DCR1f — validate target_v4 on a held-out set, then score DCR1e outputs.

DCR1e's finding was that the presupposition-inferring extractor surfaced T1
content that target_v3's spacing and vocabulary were too narrow to catch.
target_v4 (see ``target_v4.py``) widens the character windows, adds
alternatives for the four constructions target_v3 missed
(``common time X in which…``, ``time is definite … independent of``,
``regarded/perceived as simultaneous``, ``instant across the whole X``), and
adds a polarity veto so relativity-of-simultaneity denials do not fire.

The load-bearing move is the ORDER:

1. Held-out validation set generated by *sandboxed subagents that had never
   seen DCR1e outputs, target_v3, or this repository*.
2. target_v4 drafted from the DCR1e-observed constructions and from
   linguistic analysis, before the held-out sentences were read.
3. target_v4 validated against the held-out set (R2/R3 thresholds
   preregistered in DCR1F_PREREGISTRATION.md).
4. Only if R2/R3 pass, target_v4 is applied to the DCR1e consensus at each
   cut and scored against R4/R5.
5. R6 checks that Newton's Q6 hits from DCR1d still fire.

The runner checks the held-out file's SHA-256 against the preregistration's
committed digest before running, and refuses to score if they differ.

Run:
    uv run --no-sync python -m experiments.date_cut_retrodiction.run_dcr1f
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any, Final, Sequence

from experiments.date_cut_retrodiction.corpus import sources_at_or_before
from experiments.date_cut_retrodiction.cuts import CUTS
from experiments.date_cut_retrodiction.dcr1d import NEWTON_SOURCE
from experiments.date_cut_retrodiction.dcr1e import PRESUP_CONSENSUS_DIR
from experiments.date_cut_retrodiction.run_dcr1 import (
    load_extractions,
)
from experiments.date_cut_retrodiction.target_v4 import (
    compare_v3_v4,
    match_facets_v4,
)


__all__ = ["main"]

_PACKAGE: Final[Path] = Path(__file__).resolve().parent
VERDICT_PATH: Final[Path] = _PACKAGE / "results" / "dcr1f_verdict.json"
HELDOUT_PATH: Final[Path] = _PACKAGE / "heldout_simultaneity_validation.json"

#: The digest committed in DCR1F_PREREGISTRATION.md §6.  Any drift here
#: means the held-out set was regenerated (or edited) between prereg and
#: scoring, which invalidates the "target_v4 drafted before seeing the
#: held-out set" guarantee.
HELDOUT_DIGEST: Final[str] = (
    "8acdee3b9a4ede612a57a9efb37449337db38e889b2124f86992b5b1e49dc003"
)

#: R2 threshold: target_v4 must fire on at least this fraction of the
#: T1-positive held-out sentences.  Set in DCR1F_PREREGISTRATION.md §2.
R2_POSITIVE_ACCURACY: Final[float] = 0.70

#: R3 threshold: target_v4 must reject at least this fraction of the
#: T1-negative (relativity-of-simultaneity) held-out sentences.
R3_NEGATIVE_ACCURACY: Final[float] = 0.85


def _sentence_prop(text: str) -> dict[str, str]:
    return {"doc_id": "heldout", "name": "heldout_sentence", "statement": text}


def _validate_heldout() -> dict[str, Any]:
    payload_bytes = HELDOUT_PATH.read_bytes()
    digest = hashlib.sha256(payload_bytes).hexdigest()
    if digest != HELDOUT_DIGEST:
        raise SystemExit(
            f"held-out set digest mismatch: got {digest}, prereg committed "
            f"{HELDOUT_DIGEST}. Refusing to score."
        )

    heldout = json.loads(payload_bytes)
    positives = heldout["absolute_simultaneity_positive"]
    negatives = heldout["relativity_of_simultaneity_negative"]

    pos_hits = [
        match_facets_v4([_sentence_prop(text)])["T1_absolute_simultaneity"]
        for text in positives
    ]
    neg_hits = [
        match_facets_v4([_sentence_prop(text)])["T1_absolute_simultaneity"]
        for text in negatives
    ]

    pos_correct = sum(1 for hits in pos_hits if hits)
    neg_correct = sum(1 for hits in neg_hits if not hits)

    pos_accuracy = pos_correct / len(positives) if positives else 0.0
    neg_accuracy = neg_correct / len(negatives) if negatives else 0.0

    return {
        "digest": digest,
        "n_positive": len(positives),
        "n_negative": len(negatives),
        "pos_correct": pos_correct,
        "neg_correct": neg_correct,
        "pos_accuracy": pos_accuracy,
        "neg_accuracy": neg_accuracy,
        "R2_positive_accuracy": {
            "value": pos_accuracy,
            "threshold": R2_POSITIVE_ACCURACY,
            "decision": "GO" if pos_accuracy >= R2_POSITIVE_ACCURACY else "NO_GO",
        },
        "R3_negative_accuracy": {
            "value": neg_accuracy,
            "threshold": R3_NEGATIVE_ACCURACY,
            "decision": "GO" if neg_accuracy >= R3_NEGATIVE_ACCURACY else "NO_GO",
        },
    }


def _score_electrodynamics(consensus: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    by_cut: dict[str, Any] = {}
    for cut in CUTS:
        doc_ids = [s.doc_id for s in sources_at_or_before(cut.year)]
        propositions = [p for d in doc_ids for p in consensus.get(d, [])]
        hits = match_facets_v4(propositions)
        by_cut[str(cut.year)] = {
            "cut_year": cut.year,
            "label": cut.label,
            "is_placebo": cut.is_placebo,
            "n_propositions": len(propositions),
            "T1_hits": [
                {"doc_id": h["doc_id"], "name": h["name"], "statement": h["statement"]}
                for h in hits.get("T1_absolute_simultaneity", ())
            ],
            "T2_count": len(hits.get("T2_privileged_frame", ())),
            "T3_count": len(hits.get("T3_local_time_artifice", ())),
        }
    return by_cut


def _score_newton(consensus: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    props = consensus.get(NEWTON_SOURCE.doc_id, [])
    hits = match_facets_v4(props)
    return {
        "n_propositions": len(props),
        "T1_hits": [
            {"name": h["name"], "statement": h["statement"]}
            for h in hits.get("T1_absolute_simultaneity", ())
        ],
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run DCR1f validation and scoring.")
    parser.add_argument("--out", type=Path, default=VERDICT_PATH)
    args = parser.parse_args(argv)

    validation = _validate_heldout()
    consensus = load_extractions(PRESUP_CONSENSUS_DIR)
    electrodynamics = _score_electrodynamics(consensus)
    newton = _score_newton(consensus)

    r2_decision = validation["R2_positive_accuracy"]["decision"]
    r3_decision = validation["R3_negative_accuracy"]["decision"]

    t1_at_1897 = electrodynamics["1897"]["T1_hits"]
    t1_at_1880 = electrodynamics["1880"]["T1_hits"]

    r1_decision = (
        "GO"
        if validation["n_positive"] >= 30 and validation["n_negative"] >= 30
        else "NO_GO"
    )
    r4_decision = "GO" if t1_at_1897 else "NO_GO"
    r5_decision = "GO" if not t1_at_1880 else "NO_GO"
    r6_decision = "GO" if newton["T1_hits"] else "NO_GO"

    matcher_v3_v4_at_target = compare_v3_v4(
        [p for s in sources_at_or_before(1904) for p in consensus.get(s.doc_id, [])]
    )

    gates = {
        "R1_heldout_well_formed": {
            "n_positive": validation["n_positive"],
            "n_negative": validation["n_negative"],
            "decision": r1_decision,
        },
        "R2_T1_positive_accuracy": validation["R2_positive_accuracy"],
        "R3_T1_negative_rejection": validation["R3_negative_accuracy"],
        "R4_T1_fires_at_1897": {
            "n_hits": len(t1_at_1897),
            "decision": r4_decision,
        },
        "R5_T1_silent_at_1880": {
            "n_hits": len(t1_at_1880),
            "decision": r5_decision,
        },
        "R6_newton_sanity": {
            "n_hits": len(newton["T1_hits"]),
            "decision": r6_decision,
        },
    }

    all_gates_pass = all(g["decision"] == "GO" for g in gates.values())

    if all_gates_pass:
        reading = (
            "reading_A_confirmed: presupposition extraction + presupposition "
            "matcher together reach the commitment Einstein deleted. DCR2 is "
            "on the enriched consensus with target_v4."
        )
    elif r5_decision == "NO_GO":
        reading = (
            "reading_B_confirmed: extractor is projecting. T1 fired at 1880 "
            "deep placebo where the arguments requiring it do not exist. "
            "Stronger DR2-shaped framework limit."
        )
    elif r4_decision == "NO_GO":
        reading = (
            "DCR1e_over_read: target_v4 validated on the held-out register "
            "but does not fire on the DCR1e electrodynamics outputs. The "
            "'five T1 propositions' DCR1e identified were T1-adjacent but "
            "not close enough for a properly-calibrated matcher."
        )
    elif r2_decision == "NO_GO" or r3_decision == "NO_GO":
        reading = (
            "target_v4_fails_validation: matcher does not work on the "
            "held-out register. Redraft target_v5."
        )
    elif r6_decision == "NO_GO":
        reading = (
            "target_v4_lost_newton: matcher is too narrow in ways that "
            "regressed Newton coverage. Broaden and re-run."
        )
    else:
        reading = "mixed_or_inconclusive"

    verdict: dict[str, Any] = {
        "kind": "dcr1f_verdict",
        "purpose": (
            "Test whether target_v4 (widened for presuppositional phrasings) "
            "resolves the DCR1e recognizer gap. Held-out validation then "
            "score on DCR1e outputs."
        ),
        "heldout_digest": validation["digest"],
        "heldout_expected_digest": HELDOUT_DIGEST,
        "heldout_validation": validation,
        "electrodynamics_cuts": electrodynamics,
        "newton_sanity": newton,
        "matcher_v3_v4_at_1904": matcher_v3_v4_at_target,
        "gates": gates,
        "overall_decision": "GO" if all_gates_pass else "NO_GO",
        "licensed_reading": reading,
    }

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(verdict, indent=2, sort_keys=True) + "\n")
    print(json.dumps(verdict, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
