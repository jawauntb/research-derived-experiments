"""Exact combinatorial witness of the squaring-basis separation.

Companion instrument to ``papers/eml_universal_substrate/paper.md`` and
the Lean core
``formal/structural-intelligence/StructuralIntelligence/Compiler/SquaringSeparation.lean``.

Target object
-------------
The monomial ``z_n = x^(2^n)`` over two expression languages:

- ``Mul``: trees generated by ``S → x | ×(S, S)``.
- ``Sq``: trees generated by ``S → x | ×(S, S) | sq(S)`` with
  ``sq(y) = y·y`` a *definable* macro (conservative extension).

Denotation is the monomial degree.  That is a 1-D invariant, so the
fiber spectrum of ``z_n`` is dynamic-programmable.  EML denotations
have no such invariant; this toy is the laboratory, not the EML
spectrum itself.

Four seams (US-1..US-4)
-----------------------
1. Expressivity: both languages realise every positive degree.
2. Tree size: ``|t|_Mul = 2^{n+1}-1`` for every Mul-tree of degree
   ``2^n``; a Sq-tower has size ``n+1``.
3. Circuit size: any sharing DAG needs ``n`` doubling steps, and
   repeated squaring achieves ``n`` in both bases.
4. Fiber geometry under the Gibbs prior ``π(t) ∝ 4^{-|t|}``:
   the Mul fiber sits on one Catalan shell of size ``C_{2^n-1}``;
   the Sq fiber occupies every size from ``n+1`` to ``2^{n+1}-1``.
   Discovery probability is language-normalised fiber mass
   ``P(z) = Φ_z / Z``.

Partition functions (closed form)
---------------------------------
Mul generating function: ``Z_Mul = 2 - √3`` at ``x = 1/4``.
Sq generating function: ``Z_Sq = (3 - √5)/2`` at ``x = 1/4``.

Shortest-witness lower bound on the access ratio (the amended gate)::

    log2(P_Sq / P_Mul)
        ≥ 2·(2^{n+1} - n - 2) + log2(Z_Mul / Z_Sq) - log2(C_{2^n-1})

Run 1 used the un-normalised form ``2·Δsize - log2(C_{2^n-1})``
(28.79 at n=4) and omitted ``log2(Z_Mul/Z_Sq) ≈ -0.511``.  The
corrected n=4 bound is 28.28.  See ``AMENDMENT``.

US-4′ (fiber free energy predicts EML gradient recovery) is **not**
tested here.
"""

from __future__ import annotations

import math
from dataclasses import asdict, dataclass
from typing import Literal, TypedDict

N_VALUES: tuple[int, ...] = (1, 2, 3, 4)
GIBBS_BASE: int = 4
HEADLINE_N: int = 4

# Closed-form language partition functions at x = 1/4.
Z_MUL: float = 2.0 - math.sqrt(3.0)
Z_SQ: float = (3.0 - math.sqrt(5.0)) / 2.0

# Run-1 used this omitted-Z form at n=4.  Recorded, not used as a gate.
RUN1_UNNORMALISED_N4_BOUND: float = 2.0 * 26.0 - math.log2(9694845)
# 52 - log2(C_15) = 28.7917...

class AmendmentPayload(TypedDict):
    run: int
    gate_id: str
    wrong_closed_form: str
    wrong_n4_value: float
    corrected_closed_form: str
    reason: str


AMENDMENT: AmendmentPayload = {
    "run": 1,
    "gate_id": "SS_FIBER_MASS_EXCEEDS_SHORTEST_BOUND",
    "wrong_closed_form": (
        "log2(4^{2^{n+1}-n-2} / C_{2^n-1}) = 2*(2^{n+1}-n-2) - log2(C_{2^n-1})"
    ),
    "wrong_n4_value": RUN1_UNNORMALISED_N4_BOUND,
    "corrected_closed_form": (
        "2*(2^{n+1}-n-2) + log2(Z_Mul/Z_Sq) - log2(C_{2^n-1})"
    ),
    "reason": (
        "The growth threshold treated fiber mass as unnormalised Φ. "
        "Discovery probability is Φ/Z; the language partition functions "
        "differ, and log2(Z_Mul/Z_Sq) is about -0.511 bits."
    ),
}


StepKind = Literal["mul", "sq"]


@dataclass(frozen=True)
class CircStep:
    kind: StepKind
    i: int
    j: int = 0


@dataclass(frozen=True)
class FiberRow:
    n: int
    degree: int
    mul_tree_size: int
    sq_min_tree_size: int
    mul_fiber_count: int
    catalan_count: int
    mul_shell_count: int
    sq_shell_count: int
    expected_sq_shells: int
    sq_shells: tuple[int, ...]
    phi_mul: float
    phi_sq: float
    p_mul: float
    p_sq: float
    log2_ratio: float
    shortest_bound: float
    run1_unnormalised_bound: float
    circuit_steps: int
    circuit_reaches_degree: int


def catalan(n: int) -> int:
    """``C_n = (1/(n+1)) * binom(2n, n)``."""

    if n < 0:
        raise ValueError("catalan is defined for n >= 0")
    return math.comb(2 * n, n) // (n + 1)


def mul_tree_size(n: int) -> int:
    """Every Mul-tree of degree ``2^n`` has this many nodes."""

    return (1 << (n + 1)) - 1


def sq_min_tree_size(n: int) -> int:
    """Size of ``sq^n(x)``."""

    return n + 1


def shortest_access_bound(n: int) -> float:
    """Amended closed-form lower bound on ``log2(P_Sq / P_Mul)``."""

    delta = mul_tree_size(n) - sq_min_tree_size(n)
    return 2.0 * delta + math.log2(Z_MUL / Z_SQ) - math.log2(catalan((1 << n) - 1))


def run1_unnormalised_bound(n: int) -> float:
    """The incorrect bound used as the run-1 growth threshold."""

    delta = mul_tree_size(n) - sq_min_tree_size(n)
    return 2.0 * delta - math.log2(catalan((1 << n) - 1))


def _empty_table(max_size: int, max_deg: int) -> list[list[int]]:
    return [[0] * (max_deg + 1) for _ in range(max_size + 1)]


def count_mul_trees(max_size: int, max_deg: int) -> list[list[int]]:
    """``count[s][d]`` = number of Mul-trees of size ``s`` and degree ``d``."""

    count = _empty_table(max_size, max_deg)
    if max_size >= 1 and max_deg >= 1:
        count[1][1] = 1
    for size in range(2, max_size + 1):
        for left_size in range(1, size - 1):
            right_size = size - 1 - left_size
            for left_deg in range(1, max_deg + 1):
                left_c = count[left_size][left_deg]
                if left_c == 0:
                    continue
                for right_deg in range(1, max_deg - left_deg + 1):
                    count[size][left_deg + right_deg] += (
                        left_c * count[right_size][right_deg]
                    )
    return count


def count_sq_trees(max_size: int, max_deg: int) -> list[list[int]]:
    """``count[s][d]`` = number of Sq-trees of size ``s`` and degree ``d``."""

    count = _empty_table(max_size, max_deg)
    if max_size >= 1 and max_deg >= 1:
        count[1][1] = 1
    for size in range(2, max_size + 1):
        for deg in range(1, max_deg + 1):
            doubled = deg * 2
            if doubled <= max_deg:
                count[size][doubled] += count[size - 1][deg]
        for left_size in range(1, size - 1):
            right_size = size - 1 - left_size
            for left_deg in range(1, max_deg + 1):
                left_c = count[left_size][left_deg]
                if left_c == 0:
                    continue
                for right_deg in range(1, max_deg - left_deg + 1):
                    count[size][left_deg + right_deg] += (
                        left_c * count[right_size][right_deg]
                    )
    return count


def occupied_shells(count: list[list[int]], degree: int) -> tuple[int, ...]:
    return tuple(
        size for size in range(1, len(count)) if count[size][degree] > 0
    )


def fiber_mass(count: list[list[int]], degree: int, shells: tuple[int, ...]) -> float:
    return sum(count[size][degree] * (GIBBS_BASE ** (-size)) for size in shells)


def apply_step(degrees: list[int], step: CircStep) -> int:
    if step.kind == "sq":
        return degrees[step.i] * 2
    return degrees[step.i] + degrees[step.j]


def circuit_degrees(steps: tuple[CircStep, ...]) -> list[int]:
    degrees = [1]
    for step in steps:
        degrees.append(apply_step(degrees, step))
    return degrees


def circuit_max_degree(steps: tuple[CircStep, ...]) -> int:
    return max(circuit_degrees(steps))


def repeated_squaring(n: int) -> tuple[CircStep, ...]:
    """``n`` sharing-aware squarings: ``x, x^2, x^4, ..., x^(2^n)``."""

    return tuple(CircStep("sq", i) for i in range(n))


def circuit_invariant_holds(steps: tuple[CircStep, ...]) -> bool:
    """``max degree after k steps ≤ 2^k`` on this circuit."""

    degrees = [1]
    maximum = 1
    for index, step in enumerate(steps, start=1):
        if step.i >= len(degrees) or (
            step.kind == "mul" and step.j >= len(degrees)
        ):
            return False
        new = apply_step(degrees, step)
        if new > 2 * maximum:
            return False
        degrees.append(new)
        maximum = max(maximum, new)
        if maximum > (1 << index):
            return False
    return True


def alternative_circuits(n: int) -> tuple[tuple[CircStep, ...], ...]:
    """A few non-tower circuits used as a circuit-bound stress set."""

    if n <= 0:
        return ()
    left_muls = tuple(CircStep("mul", i, 0) for i in range(n))
    self_muls = tuple(CircStep("mul", i, i) for i in range(n))
    return (left_muls, self_muls, repeated_squaring(n))


def evaluate_row(n: int) -> FiberRow:
    degree = 1 << n
    max_size = mul_tree_size(n)
    min_sq = sq_min_tree_size(n)
    mul_count = count_mul_trees(max_size, degree)
    sq_count = count_sq_trees(max_size, degree)
    mul_shells = occupied_shells(mul_count, degree)
    sq_shells = occupied_shells(sq_count, degree)
    phi_mul = catalan(degree - 1) * (GIBBS_BASE ** (-max_size))
    phi_sq = fiber_mass(sq_count, degree, sq_shells)
    p_mul = phi_mul / Z_MUL
    p_sq = phi_sq / Z_SQ
    steps = repeated_squaring(n)
    return FiberRow(
        n=n,
        degree=degree,
        mul_tree_size=max_size,
        sq_min_tree_size=min_sq,
        mul_fiber_count=mul_count[max_size][degree],
        catalan_count=catalan(degree - 1),
        mul_shell_count=len(mul_shells),
        sq_shell_count=len(sq_shells),
        expected_sq_shells=max_size - min_sq + 1,
        sq_shells=sq_shells,
        phi_mul=phi_mul,
        phi_sq=phi_sq,
        p_mul=p_mul,
        p_sq=p_sq,
        log2_ratio=math.log2(p_sq / p_mul),
        shortest_bound=shortest_access_bound(n),
        run1_unnormalised_bound=run1_unnormalised_bound(n),
        circuit_steps=len(steps),
        circuit_reaches_degree=circuit_degrees(steps)[-1],
    )


def expressivity_holds(max_degree: int) -> bool:
    """Every degree in ``1..max_degree`` is realised in both languages."""

    mul_count = count_mul_trees(2 * max_degree - 1, max_degree)
    sq_count = count_sq_trees(2 * max_degree - 1, max_degree)
    for degree in range(1, max_degree + 1):
        if sum(row[degree] for row in mul_count) == 0:
            return False
        if sum(row[degree] for row in sq_count) == 0:
            return False
    return True


def evaluate_gates(rows: tuple[FiberRow, ...]) -> dict[str, bool]:
    headline = next(row for row in rows if row.n == HEADLINE_N)
    circuit_ok = all(
        row.circuit_steps == row.n
        and row.circuit_reaches_degree == row.degree
        and circuit_invariant_holds(repeated_squaring(row.n))
        and all(circuit_invariant_holds(steps) for steps in alternative_circuits(row.n))
        for row in rows
    )
    return {
        "SS_EXPRESSIVITY_CONSERVATIVE_EXTENSION": expressivity_holds(1 << HEADLINE_N),
        "SS_TREE_SIZE_EXACT": all(
            row.mul_tree_size == mul_tree_size(row.n)
            and row.sq_min_tree_size == sq_min_tree_size(row.n)
            for row in rows
        ),
        "SS_CATALAN_SINGLE_SHELL": all(
            row.mul_fiber_count == row.catalan_count
            and row.mul_shell_count == 1
            for row in rows
        ),
        "SS_CIRCUIT_SIZE_THETA_N": circuit_ok,
        "SS_FIBER_MASS_EXCEEDS_SHORTEST_BOUND": all(
            row.log2_ratio + 1e-12 >= row.shortest_bound for row in rows
        )
        and headline.log2_ratio >= 28.28,
        "SS_SHELL_OCCUPANCY": all(
            row.sq_shell_count == row.expected_sq_shells
            and row.sq_shells == tuple(range(row.sq_min_tree_size, row.mul_tree_size + 1))
            for row in rows
        )
        and headline.sq_shell_count == 27,
    }


class HeadlinePayload(TypedDict):
    p_mul: float
    p_sq: float
    log2_ratio: float
    shortest_bound: float
    mul_fiber_count: int
    sq_shell_count: int


class BenchmarkPayload(TypedDict):
    status: Literal["pass", "fail"]
    experiment_id: str
    run_id: str
    n_values: list[int]
    gibbs_base: int
    z_mul: float
    z_sq: float
    headline_n: int
    headline: HeadlinePayload
    rows: list[dict[str, object]]
    gates: dict[str, bool]
    amendment: AmendmentPayload
    untested: dict[str, str]
    citations_pending_verification: list[str]


def evaluate_benchmark() -> BenchmarkPayload:
    rows = tuple(evaluate_row(n) for n in N_VALUES)
    gates = evaluate_gates(rows)
    headline = next(row for row in rows if row.n == HEADLINE_N)
